"""Makes server/card.js: the picture X shows under a shared FORK BOMB post (1200 x 630 PNG, base64).

  .venv/bin/python tools/make_card.py
Built from tools/out/grid1.png (the 2x screenshots: title top left, a blast bottom left).
"""
import base64, io, os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
grid = Image.open(os.path.join(ROOT, "tools/out/grid1.png")).convert("RGB")
title = grid.crop((0, 0, 640, 420))
blast = grid.crop((0, 476, 640, 876))
W, H = 1200, 630
img = Image.new("RGB", (W, H), (11, 11, 20))
img.paste(title.resize((560, 368), Image.NEAREST), (30, 150))
img.paste(blast.resize((560, 350), Image.NEAREST), (610, 160))
d = ImageDraw.Draw(img)
font = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"
d.text((30, 20), "FORK BOMB", font=ImageFont.truetype(font, 64), fill=(255, 255, 255))
d.text((32, 96), "bomb-maze arcade on the Solana Breakpoint badge", font=ImageFont.truetype(font, 28), fill=(138, 138, 150))
d.text((W - 30, H - 22), "blast forks, dodge rugs and MEV bots", font=ImageFont.truetype(font, 28), fill=(20, 241, 149), anchor="rs")
buf = io.BytesIO()
img.save(buf, "PNG", optimize=True)
img.save(os.path.join(ROOT, "tools/out/card.png"))
b64 = base64.b64encode(buf.getvalue()).decode()
with open(os.path.join(ROOT, "server/card.js"), "w") as f:
    f.write("// Generated by tools/make_card.py: the X share picture, 1200 x 630 PNG.\n")
    f.write(f"export const CARD_B64 = '{b64}';\n")
print(len(buf.getvalue()), "bytes png")
